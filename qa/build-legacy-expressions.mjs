import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const sharp=require(process.env.JELLY_SHARP_MODULE||'sharp');
const source='reference/generated-legacy-condition-v2.png';
const base='reference/runtime/npc-sprites.webp';
async function crop(file,region){
  const {data,info}=await sharp(file).extract(region).ensureAlpha().raw().toBuffer({resolveWithObject:true});
  let left=info.width,top=info.height,right=-1,bottom=-1;
  for(let y=0;y<info.height;y++)for(let x=0;x<info.width;x++){
    const i=(y*info.width+x)*4;
    if(data[i+3]<32){data[i+3]=0;continue;}
    left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);
  }
  assert.ok(right>left&&bottom>top,'Nonempty sprite');
  const bounds={left,top,width:right-left+1,height:bottom-top+1};
  return {bounds,buffer:await sharp(data,{raw:info}).extract(bounds).png().toBuffer()};
}
const normal=await sharp(base).metadata(),edited=await sharp(source).metadata();
assert.ok(edited.hasAlpha,'Expression sheet must be transparent');
const frameWidth=normal.width/3,frameHeight=normal.height;
const layers=[],registration=[],topOffsets=[],footOffsets=[];
for(let frame=0;frame<3;frame++){
  const target=await crop(base,{left:frame*frameWidth,top:0,width:frameWidth,height:frameHeight});
  const left=Math.floor(frame*edited.width/3),right=Math.floor((frame+1)*edited.width/3);
  const pose=await crop(source,{left,top:0,width:right-left,height:edited.height});
  const scale=Math.min(target.bounds.width/pose.bounds.width,target.bounds.height/pose.bounds.height);
  const width=Math.round(pose.bounds.width*scale),height=Math.round(pose.bounds.height*scale);
  const x=target.bounds.left+Math.floor((target.bounds.width-width)/2),y=target.bounds.top+target.bounds.height-height;
  layers.push({input:await sharp(pose.buffer).resize(width,height).png().toBuffer(),left:frame*frameWidth+x,top:y});
  topOffsets.push(Number((84-target.bounds.top/frameHeight*132).toFixed(2)));
  footOffsets.push(Number((-84+(target.bounds.top+target.bounds.height)/frameHeight*132).toFixed(2)));
  registration.push({frame,target:target.bounds,source:pose.bounds,width,height,left:x,top:y});
}
const atlas=await sharp({create:{width:normal.width,height:frameHeight,channels:4,background:{r:0,g:0,b:0,alpha:0}}}).composite(layers).png().toBuffer();
await fs.writeFile('reference/runtime/npc-condition-v2.png',atlas);
await sharp(atlas).webp({lossless:true}).toFile('reference/runtime/npc-condition-v2.webp');
await fs.writeFile('reference/art-layouts/legacy-expression-manifest-v2.json',JSON.stringify({source,base,frameWidth,frameHeight,registration,topOffsets,footOffsets},null,2)+'\n');
await fs.writeFile('src/game/NPCSpriteLayout.js',`// Generated by qa/build-legacy-expressions.mjs from the normal atlas alpha bounds.\nexport const LEGACY_NPC_LAYOUT = Object.freeze({\n  topOffsets: Object.freeze(${JSON.stringify(topOffsets)}),\n  footOffsets: Object.freeze(${JSON.stringify(footOffsets)})\n});\n`);
console.log('PASS: three concerned poses preserve normal sprite scale and foot registration.');
