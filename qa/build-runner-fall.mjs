import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const sharp=require(process.env.JELLY_SHARP_MODULE||'sharp');
const source='reference/generated-runner-fall-v1.png';
const {data,info}=await sharp(source).ensureAlpha().raw().toBuffer({resolveWithObject:true});
const columnCounts=Array.from({length:info.width},(_,x)=>{
  let count=0;for(let y=0;y<info.height;y++)if(data[(y*info.width+x)*4+3]>=32)count++;
  return count;
});
const seams=[0];
for(const fraction of [1/3,2/3]){
  const nominal=Math.round(info.width*fraction);
  let seam=nominal,best=Infinity;
  for(let x=nominal-Math.round(info.width*.08);x<=nominal+Math.round(info.width*.08);x++){
    const score=columnCounts[x]*info.width+Math.abs(x-nominal);
    if(score<best){best=score;seam=x;}
  }
  assert.equal(columnCounts[seam],0,'Frame boundary must be transparent');seams.push(seam);
}
seams.push(info.width);
const frames=[];
for(let col=0;col<3;col++){
  let left=info.width,top=info.height,right=0,bottom=0;
  for(let y=0;y<info.height;y++)for(let x=seams[col];x<seams[col+1];x++){
    if(data[(y*info.width+x)*4+3]<32)continue;
    left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);
  }
  assert.ok(right>left&&bottom>top);
  const bounds={left,top,width:right-left+1,height:bottom-top+1};
  frames.push({bounds,buffer:await sharp(source).extract(bounds).png().toBuffer()});
}
const scale=Math.min(300/frames[0].bounds.height,244/Math.max(...frames.map(frame=>frame.bounds.width)));
const layers=[],registration=[];
for(let col=0;col<3;col++){
  const frame=frames[col],width=Math.round(frame.bounds.width*scale),height=Math.round(frame.bounds.height*scale);
  const left=col*256+Math.floor((256-width)/2),top=380-height;
  layers.push({input:await sharp(frame.buffer).resize(width,height).png().toBuffer(),left,top});
  registration.push({col,width,height,left,top,source:frame.bounds});
}
const row=await sharp({create:{width:768,height:384,channels:4,background:{r:0,g:0,b:0,alpha:0}}}).composite(layers).png().toBuffer();
const prior=await sharp('reference/runtime/sports-injury-v3.png').ensureAlpha().raw().toBuffer();
// Append raw pixels to avoid an alpha composite round-trip changing old edges.
const combined=Buffer.concat([prior,await sharp(row).ensureAlpha().raw().toBuffer()]);
const atlas=await sharp(combined,{raw:{width:768,height:1920,channels:4}}).png().toBuffer();
const raw=await sharp(atlas).raw().toBuffer();
assert.ok(raw.subarray(0,prior.length).equals(prior),'Existing twelve poses remain pixel-identical');
await fs.writeFile('reference/runtime/sports-injury-v4.png',atlas);
await sharp(atlas).webp({lossless:true}).toFile('reference/runtime/sports-injury-v4.webp');
const previous=JSON.parse(await fs.readFile('reference/art-layouts/art-refinement-manifest-v3.json'));
const offsets=[...previous.injuryTopOffsets,registration.map(frame=>Number((144-frame.top*180/384).toFixed(2)))];
await fs.writeFile('src/game/InjurySpriteLayout.js',`// Generated by qa/build-runner-fall.mjs from registered alpha bounds.\nexport const INJURY_TOP_OFFSETS = Object.freeze(${JSON.stringify(offsets)}.map(row => Object.freeze(row)));\n`);
await fs.writeFile('reference/art-layouts/runner-fall-registration-v1.json',JSON.stringify({source,seams,scale,registration,injuryTopOffsets:offsets},null,2)+'\n');
console.log('PASS: runner fall appended as row 4; all previous poses unchanged; shared scale and foot baseline.');
